const assert = require('node:assert/strict');
const { instrumentViewerBundle, terrainReady } = require('../../games/minecraft/viewer_readiness.cjs');
assert.throws(() => instrumentViewerBundle('other entry point'));
assert.throws(() => instrumentViewerBundle('const u=new r(l);const u=new r(l);'));
const source='before;const u=new r(l);after;';
const observed=instrumentViewerBundle(source);
assert.ok(observed.startsWith('before;const u=new r(l);'));
assert.ok(observed.endsWith('after;'));
assert.ok(observed.includes('globalThis.sub01MinecraftViewer=u;'));
assert.equal(terrainReady(),false);
const world={loadedChunks:{'0,0':true},sectionsOutstanding:new Set(),material:{map:{image:{width:1024}}},sectionMeshs:{'0,0,0':{geometry:{attributes:{position:{count:36}}}}}};
globalThis.sub01MinecraftViewer={world};
assert.equal(terrainReady(),true);
world.sectionsOutstanding.add('0,0,0');assert.equal(terrainReady(),false);
world.sectionsOutstanding.clear();world.material.map=null;assert.equal(terrainReady(),false);
world.material.map={image:{width:1024}};world.sectionMeshs={};assert.equal(terrainReady(),false);
world.sectionMeshs={'0,0,0':{geometry:{attributes:{position:{count:0}}}}};assert.equal(terrainReady(),false);
world.loadedChunks={};assert.equal(terrainReady(),false);
delete globalThis.sub01MinecraftViewer;
console.log('Minecraft real terrain mesh, worker completion and texture readiness checks passed');

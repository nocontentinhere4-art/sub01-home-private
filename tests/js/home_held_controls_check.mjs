import assert from "node:assert/strict";
import { HeldControls } from "../../web/house/held_controls.mjs";
const input = new HeldControls();
assert.equal(input.changed, false);
input.set("ArrowUp", -1);
const first = input.version;
input.set("ArrowUp", -1);
assert.equal(input.version, first, "Key-repeat does not multiply a hold");
assert.equal(input.direction, -1);
input.acknowledge(first);
assert.equal(input.active, true, "A delivered command does not release the hold");
input.set("pointer:7", 1);
assert.equal(input.direction, 0, "Opposing holds cancel");
input.release("ArrowUp");
assert.equal(input.direction, 1, "Remaining pointer keeps controlling the paddle");
const inFlight = input.version;
input.release("pointer:7");
input.acknowledge(inFlight);
assert.equal(input.changed, true, "A stale response cannot discard a newer stop");
assert.equal(input.direction, 0);
input.acknowledge(input.version);
assert.equal(input.changed, false);
input.set("ArrowDown", 1);
input.clear();
assert.equal(input.active, false, "Closing or losing focus releases controls");
assert.equal(input.changed, true, "The final neutral command is still pending");
console.log("PASS: continuous holds, opposing inputs, release, focus loss and in-flight responses");

const timers = [], pulse = new HeldControls();
pulse.pulse('activation', -1, callback => timers.push(callback));
const submitted = pulse.version;
pulse.acknowledge(submitted);
pulse.clear();
assert.equal(pulse.direction, 0);
assert.equal(pulse.changed, true, 'Closing a keyboard activation must queue a neutral release');
pulse.pulse('activation', 1, callback => timers.push(callback));
timers[0]();
assert.equal(pulse.direction, 1, 'An old pulse timer cannot release a newer activation');
timers[1]();
assert.equal(pulse.direction, 0);
assert.equal(pulse.active, false);
console.log('PASS: accessible activation ownership, close release and stale timer identity');

import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as T from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {attachUpperCabinetDoors} from '../../web/house/cabinet_doors.mjs';
import {staticBakeScene} from '../../web/house/balcony_access.mjs';
const data=fs.readFileSync(new URL('../../web/house/assets/kitchen-cabinet-original/cabinet.glb',import.meta.url));
const gltf=await new GLTFLoader().parseAsync(data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength),'');
const root=gltf.scene;root.position.set(-2.2,2.05,-3.71);root.updateMatrixWorld(true);
const before=new Map();root.traverse(o=>{if(o.isMesh)before.set(o.name,o.matrixWorld.clone());});
const interactions=[],requests=[];
const controller=attachUpperCabinetDoors(T,root,{interactions,getPositions:()=>[[-1.8,1.65,-2]],onToggle:(i,open)=>{requests.push([i,open]);return true;}});
root.updateMatrixWorld(true);root.traverse(o=>{if(o.isMesh)assert(o.matrixWorld.equals(before.get(o.name)),'exact original closed transform for '+o.name);});
assert(interactions[0].fn());assert.deepEqual(requests,[[0,true]]);assert.equal(controller.doors[0].target,0,'request waits for shared server state');
controller.setTargets([true,false,false,false]);for(let i=0;i<180;i++)controller.update(1/60);
assert(controller.doors[0].angle< -1.5);assert.equal(controller.doors[1].angle,0);
const scene=new T.Scene();scene.add(root);const staticCopy=staticBakeScene(scene),meshes=[];staticCopy.traverse(o=>{if(o.isMesh)meshes.push(o.name);});
assert.deepEqual(meshes,['Cabinet_carcass'],'fresh source keeps hollow static carcass, excludes every moving door/pull');
console.log('PASS actual GLB: exact closed transforms, original parented handles, server-authoritative target and fresh bake removes all moving leaves/pulls only.');

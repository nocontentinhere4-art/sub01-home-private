import assert from 'node:assert/strict';
import * as T from '../../web/house/vendor/three.module.js';
import {sceneBudget}from '../../web/house/runtime_budget.mjs';
const scene=new T.Scene(),geometry=new T.BoxGeometry();
const map=new T.Texture({width:1024,height:1024});map.generateMipmaps=true;
const copy=map.clone();copy.repeat.set(3,4);
const material=new T.MeshStandardMaterial({map}),other=new T.MeshStandardMaterial({map:copy});
scene.add(new T.Mesh(geometry,material),new T.Mesh(geometry,other));
let b=sceneBudget(scene,{info:{render:{triangles:24,calls:2},memory:{textures:1}}});
assert.equal(b.uniqueGeometries,1);assert.equal(b.sceneTriangles,24);assert.equal(b.uploadVariants,1,'matrix repeats share texture Source storage');
assert.equal(b.decodedTextureBytes,5592404,'exact square RGBA+mip allocation estimate');assert.equal(b.actualFrameTriangles,24);
copy.flipY=!map.flipY;b=sceneBudget(scene);assert.equal(b.uploadVariants,2,'different upload keys require separate allocations');
const hdr=new T.DataTexture(new Uint16Array(10*20*4),10,20,T.RGBAFormat,T.HalfFloatType);hdr.generateMipmaps=false;
scene.add(new T.Mesh(geometry,new T.ShaderMaterial({uniforms:{tHDR:{value:hdr}}})));
b=sceneBudget(scene);assert.equal(b.decodedTextureBytes,5592404*2+1600);
const before=[...geometry.attributes.position.array];sceneBudget(scene);assert.deepEqual([...geometry.attributes.position.array],before);
assert.equal(b.largestTextureUploads[0].dimensions[0].width,1024);
assert.equal(b.largestTextureUploads[0].bytes,5592404);
assert.equal(b.largestTextureUploads.at(-1).dimensions[0].componentBytes,2);
const extra=new T.DataTexture(new Uint16Array(8*9*4),8,9,T.RGBAFormat,T.HalfFloatType);extra.generateMipmaps=false;
assert.equal(sceneBudget(scene,null,[extra]).decodedTextureBytes,b.decodedTextureBytes+576,'night maps supplied separately are counted');
map.name='https://private.example/image?secret=do-not-read';map.image.src='data:image/png;base64,do-not-read';
const hidden=new T.Texture({width:2,height:2});
material['https://private.example/?token=do-not-read']=hidden;
const diagnostic=sceneBudget(scene);
assert.ok(!JSON.stringify(diagnostic).includes('do-not-read'),'diagnostics do not expose names, URLs, queries or image data');
assert.ok(diagnostic.largestTextureUploads.some(r=>r.roles.includes('map')));
assert.ok(diagnostic.largestTextureUploads.length<=12);
console.log('PASS: shared geometries/texture Sources and upload-key differences, exact mip/half-float estimates, shader-uniform maps, actual renderer counters, read-only behavior');
